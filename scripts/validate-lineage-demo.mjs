import assert from 'node:assert/strict';
import {rootId,visibleNodes,toggleBranch,recordRelations} from '../assets/signals-2026/lineage-graph-model.mjs';
const ids=state=>visibleNodes(state).map(n=>n.id);
let state=new Set([rootId]);
assert.equal(ids(state).length,4);
state=toggleBranch(state,'CL-001-01');
assert.equal(ids(state).length,5);
state=toggleBranch(state,'CX-001');
assert.equal(ids(state).length,7);
state=toggleBranch(state,'PV-001');
assert.equal(ids(state).length,9);
state=toggleBranch(state,'CL-001-01');
assert.equal(ids(state).length,6);
assert(!ids(state).includes('CX-001-01'),'Collapsing an ancestor hides expanded descendants');
assert(ids(state).includes('DNA-001'),'The independent upstream branch stays expanded');
state=toggleBranch(state,'CL-001-01');
assert.equal(ids(state).length,9,'Reopening restores the branch state');
assert.deepEqual(ids(toggleBranch(state,rootId)),ids(state),'Current material cannot be collapsed');
assert.deepEqual(ids(toggleBranch(state,'DNA-001')),ids(state),'Leaf nodes cannot expand');
assert.deepEqual(recordRelations('PV-001').parents.map(n=>n.id),['DNA-001','DNA-002']);
assert.deepEqual(recordRelations('PV-001').children.map(n=>n.id),['CL-001']);
assert.deepEqual(recordRelations('CL-001').parents.map(n=>n.id),['PV-001']);
assert.deepEqual(recordRelations('CL-001-01').children.map(n=>n.id),['CX-001']);
console.log('Lineage demo: branch visibility and record direction checks passed');
